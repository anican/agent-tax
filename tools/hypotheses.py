"""hypotheses.py — evaluate H1–H4 with the operationalization pre-registered in
REPORT.md ("significant" = >= 5% of sampled on-CPU time aggregated across all
replayed commands, or >= 10% in at least one command class; "most" = > 50% of
summed episode wall-clock and > 50% in the majority of tasks).
Writes results/summary/hypotheses.md."""
import os, sys
import numpy as np, pandas as pd
sys.path.insert(0, os.path.dirname(__file__))
import analyze
OUT = analyze.OUT

def metric(cat, mask_fn, keys):
    df = cat.copy(); df["hit"] = mask_fn(df) * df["n"]
    g = df.groupby(keys + ["rep"])[["hit", "n"]].sum(); g["pct"] = g.hit / g.n * 100
    return g["pct"].groupby(level=keys).agg(["mean", "std"])

def evaluate(cat, name, fn):
    out = {}
    for scope, sub in (("all replayed commands", cat), ("episode commands only", cat[cat.phase == "solve"])):
        s = sub.copy(); s["all"] = "ALL"
        agg = metric(s, fn, ["all"]).loc["ALL"]; bycls = metric(s, fn, ["cls"])
        top = bycls["mean"].idxmax()
        out[scope] = (agg["mean"], agg["std"], top, bycls.loc[top, "mean"], bycls)
    return out

def fmt(name, res):
    lines = [f"### {name}", "", "| Scope | Aggregate share (mean ± std over 3 reps) | Largest class share | Meets 'significant'? |", "|---|---|---|---|"]
    for scope, (m, s, top, tm, _) in res.items():
        sig = "yes" if (m >= 5 or tm >= 10) else "no"
        lines.append(f"| {scope} | {m:.2f} ± {s:.2f} % | {tm:.1f} % ({top}) | {sig} |")
    by = res["all replayed commands"][4]
    lines += ["", "Per class (all replayed commands): " + ", ".join(f"{k} {v:.1f}%" for k, v in by["mean"].items()), ""]
    return "\n".join(lines)

def main():
    cat, *_ = analyze.load_profiles()
    md = ["# Hypothesis evaluation (generated by tools/hypotheses.py)", ""]
    tv = pd.read_csv(f"{OUT}/time_view_per_task.csv")
    share = tv.model_loop_s / tv.episode_s * 100
    tot = tv.model_loop_s.sum() / tv.episode_s.sum() * 100
    md += ["### H1 — model/loop time vs tool execution", "",
           f"Summed over {len(tv)} episodes: model + loop = {tv.model_loop_s.sum():.0f} s of {tv.episode_s.sum():.0f} s "
           f"= **{tot:.1f} %**; tool execution = {tv.tool_total_s.sum()/tv.episode_s.sum()*100:.1f} %; "
           f"instrumentation (snapshots) = {tv.snapshot_s.sum()/tv.episode_s.sum()*100:.1f} %.",
           f"Tasks where model + loop > 50 %: **{int((share > 50).sum())} of {len(tv)}** "
           f"(per task: " + ", ".join(f"{t.split('__')[1]} {v:.0f}%" for t, v in zip(tv.task, share)) + ").", ""]
    sched = lambda d: (d["cat"] == "scheduling/context switch").astype(float)
    sched_kernel = lambda d: ((d["cat"] == "scheduling/context switch") & (d["sub"] == "scheduler / futex")).astype(float)
    mem = lambda d: (d["cat"] == "memory movement").astype(float)
    life = lambda d: d["cat"].isin(["process lifecycle", "interpreter startup/imports"]).astype(float)
    life_orig = lambda d: (d["cat"].isin(["process lifecycle", "interpreter startup/imports"]) | (d["rule"] == "U6v")).astype(float)
    life_only = lambda d: (d["cat"] == "process lifecycle").astype(float)
    imp_only = lambda d: (d["cat"] == "interpreter startup/imports").astype(float)
    md.append(fmt("H2 — scheduling / context switch / threading (category total)", evaluate(cat, "", sched)))
    md.append(fmt("H2 (component) — kernel scheduler + futex only", evaluate(cat, "", sched_kernel)))
    md.append(fmt("H3 — memory movement (memcpy/memmove/memset, kernel copy/zero)", evaluate(cat, "", mem)))
    md.append(fmt("H4 — process lifecycle + interpreter startup/imports (main taxonomy; CPUID detection counted as virtualization)", evaluate(cat, "", life)))
    md.append(fmt("H4 (variant) — same, with glibc CPUID feature detection counted as dynamic linking (taxonomy before D16)", evaluate(cat, "", life_orig)))
    md.append(fmt("H4 (component) — process lifecycle only", evaluate(cat, "", life_only)))
    md.append(fmt("H4 (component) — interpreter startup/imports only", evaluate(cat, "", imp_only)))
    open(f"{OUT}/hypotheses.md", "w").write("\n".join(md) + "\n")
    print("\n".join(md))

if __name__ == "__main__":
    main()
